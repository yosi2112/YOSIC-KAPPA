param([string]$ToolDirectory = '')
$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../..'))
$src = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$out = Join-Path $root 'out/dos'
if (-not $ToolDirectory) { $ToolDirectory = Join-Path $root 'out/build' }
$assembler = Join-Path $ToolDirectory 'yosic-as.exe'
if (-not (Test-Path -LiteralPath $assembler)) { throw "Assembler not found: $assembler" }
New-Item -ItemType Directory -Force -Path $out | Out-Null

# The portable assembler predates INCLUDE. Expand includes without changing sources.
function Expand-Source([string]$path) {
    $lines = foreach ($line in [IO.File]::ReadAllLines($path)) {
        if ($line -match '^\s*INCLUDE\s+([^;]+)') {
            $name = $Matches[1].Trim().Trim('"')
            if ($name -eq 'kernel.inc') { Expand-Source (Join-Path $out $name) }
            else { Expand-Source (Join-Path (Split-Path $path) $name) }
        } else { $line }
    }
    return $lines
}
function Assemble([string]$name) {
    $expanded = Join-Path $out "$name-expanded.asm"
    [IO.File]::WriteAllLines($expanded, [string[]](Expand-Source (Join-Path $src "$name.asm")))
    & $assembler $expanded -o (Join-Path $out "$name.bin") --map (Join-Path $out "$name.map")
    if ($LASTEXITCODE -ne 0) { throw "Assembler failed: $name ($LASTEXITCODE)" }
}

Assemble 'dos'
$kernel = [IO.File]::ReadAllBytes((Join-Path $out 'dos.bin'))
if ($kernel.Length -lt 4 -or $kernel.Length -gt 65528 -or $kernel.Length % 4) {
    throw 'Invalid kernel size/alignment'
}
[uint64]$checksum = 0
for ($i = 0; $i -lt $kernel.Length; $i += 4) {
    $checksum = ($checksum + [BitConverter]::ToUInt32($kernel, $i)) -band 0xffffffffL
}
$sectors = [int][Math]::Ceiling($kernel.Length / 512.0)
$metadata = @(
    '; Generated by src/dos/tools/build.ps1 from out/dos/dos.bin. Do not edit.'
    "KernelBytes EQU $($kernel.Length)"
    "KernelSectors EQU $sectors"
    ('KernelChecksum EQU 0{0:X8}h' -f $checksum)
)
[IO.File]::WriteAllLines((Join-Path $out 'kernel.inc'), $metadata)
Assemble 'loader'
$assembledLoader = [IO.File]::ReadAllBytes((Join-Path $out 'loader.bin'))
if ($assembledLoader.Length -le 8192) { throw 'Loader has no payload at ORG 2000h' }
[byte[]]$loader = $assembledLoader[8192..($assembledLoader.Length - 1)]
if ($loader.Length -gt 8192 -or $loader.Length % 4) { throw 'Invalid IPL payload size/alignment' }
[IO.File]::WriteAllBytes((Join-Path $out 'loader.bin'), $loader)
$python = Get-Command python -ErrorAction SilentlyContinue
if (-not $python) { throw 'Python is required to generate the image' }
& $python.Source (Join-Path $PSScriptRoot 'make-image.py') $out
if ($LASTEXITCODE -ne 0) { throw 'Image generation failed' }
Write-Output "DOS image: $(Join-Path $out 'dos.d88')"
Write-Output "Kernel: $($kernel.Length) bytes; loader: $($loader.Length) bytes"
